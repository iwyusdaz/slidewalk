#!/usr/bin/env python3
"""slidewalk PPTX builder — deck JSON -> native .pptx via python-pptx.

Design notes:
- Uses the blank slide layout and adds real text frames (title + body) so the
  output is editable in PowerPoint/Keynote/Slides, not screenshots.
- Speaker notes are written per slide via notes_slide.notes_text_frame.
- Checkpoint slides carry the auto-generated retrieval prompt plus its source
  slide, so no orphan questions.
- Images are an HTML-deck feature; PPTX output adds a labelled text placeholder
  ("[Figure: <alt>]") instead -- documented limitation, see README.

Known limitation (documented, not hidden): PPTX accessibility (reading order,
PowerPoint's own Accessibility Checker) can be recommended in the facilitator
guide but is not enforced from code here. The WCAG gates apply to the HTML
deck; the PPTX shares the same text, structure and notes.
"""
import argparse
import json
import sys

from pptx import Presentation
from pptx.util import Inches, Pt, Emu
from pptx.dml.color import RGBColor

# 16:9 slide size
SLIDE_W = Inches(13.333)
SLIDE_H = Inches(7.5)

# Theme-agnostic, high-contrast palette (dark text on light slides so the
# default PowerPoint theme does not fight us).
FG = RGBColor(0x1B, 0x27, 0x33)
MUTED = RGBColor(0x4C, 0x5A, 0x68)
ACCENT = RGBColor(0x0B, 0x5F, 0xA5)
PANEL_BG = RGBColor(0xEA, 0xF1, 0xF7)


def add_title(slide, text, size=32, color=FG, top=Inches(0.5)):
    box = slide.shapes.add_textbox(Inches(0.7), top, SLIDE_W - Inches(1.4), Inches(1.2))
    tf = box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    run = p.add_run()
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = True
    run.font.color.rgb = color
    return box


def add_body(slide, items, top=Inches(1.9), size=20, color=FG):
    box = slide.shapes.add_textbox(Inches(0.9), top, SLIDE_W - Inches(1.8), SLIDE_H - top - Inches(1.0))
    tf = box.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        run = p.add_run()
        run.text = item
        run.font.size = Pt(size)
        run.font.color.rgb = color
        p.space_after = Pt(10)
    return box


def set_notes(slide, deck, s):
    notes = []
    if s.get("notes"):
        notes.append(s["notes"])
    if s.get("objective"):
        notes.append(f"Objective: {s['objective']}")
    if not notes:
        notes.append("(No speaker notes in the source outline. Add `notes:` lines to the outline slide.)")
    slide.notes_slide.notes_text_frame.text = "\n\n".join(notes)


def build(deck, out_path):
    prs = Presentation()
    prs.slide_width = SLIDE_W
    prs.slide_height = SLIDE_H
    blank = prs.slide_layouts[6]  # blank layout; we add real text frames

    for idx, s in enumerate(deck["slides"], start=1):
        slide = prs.slides.add_slide(blank)
        kind = s.get("kind", "content")
        core = prs.core_properties
        core.title = deck.get("title", "")
        core.author = deck.get("author") or "slidewalk 1.0"
        core.language = deck.get("lang", "en")
        core.comments = (
            "Generated by slidewalk 1.0 from an accessible deck outline. "
            "Speaker notes are per slide; checkpoint questions are auto-generated retrieval prompts."
        )

        if kind == "title":
            add_title(slide, s["title"], size=40, top=Inches(2.2))
            if s.get("bullets"):
                add_body(slide, s["bullets"], top=Inches(3.4), size=18, color=MUTED)
        elif kind == "section":
            add_title(slide, s["title"], size=36, top=Inches(2.4), color=ACCENT)
            if s.get("bullets"):
                add_body(slide, s["bullets"], top=Inches(3.5), size=18, color=MUTED)
        elif kind == "checkpoint":
            label = add_title(slide, "Checkpoint — auto-generated retrieval prompt", size=14, color=ACCENT, top=Inches(0.4))
            add_title(slide, s["title"], size=32, top=Inches(1.0))
            qbox = slide.shapes.add_textbox(Inches(0.9), Inches(2.3), SLIDE_W - Inches(1.8), Inches(2.4))
            tf = qbox.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            run = p.add_run()
            run.text = s.get("question", "")
            run.font.size = Pt(24)
            run.font.bold = True
            run.font.color.rgb = FG
            extra = [f"Drawn from: “{s.get('sourceSlide', '')}”"] + [
                b for b in s.get("bullets", [])
            ]
            add_body(slide, extra, top=Inches(4.9), size=14, color=MUTED)
        else:  # content
            add_title(slide, s["title"])
            body = list(s.get("bullets", []))
            if s.get("image"):
                alt = s["image"].get("alt", "")
                body.append(f"[Figure: {alt}]" if alt else "[Figure]")
            if not body:
                body.append("(Add bullet lines to this outline slide.)")
            add_body(slide, body)

        set_notes(slide, deck, s)

    prs.save(out_path)


def main():
    ap = argparse.ArgumentParser(description="deck JSON -> PPTX")
    ap.add_argument("--json", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    with open(args.json, "r", encoding="utf-8") as f:
        deck = json.load(f)
    if not deck.get("slides"):
        sys.exit("slidewalk-pptx: deck has no slides")
    build(deck, args.out)
    print(f"slidewalk-pptx: wrote {args.out} — {len(deck['slides'])} slides")


if __name__ == "__main__":
    main()
